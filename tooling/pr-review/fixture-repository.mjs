function withoutExtension(path) {
	return path.replace(/\.(?:d\.)?[cm]?[jt]sx?$/, "");
}

function callerFor(path) {
	if (!/\.(?:d\.)?[cm]?[jt]sx?$/.test(path) || path.endsWith(".d.ts"))
		return {};
	const depth = "test/review-context.test.ts".split("/").length - 1;
	const relative = posix.relative("test", withoutExtension(path));
	const specifier = relative.startsWith(".") ? relative : `./${relative}`;
	return {
		"test/review-context.test.ts": `import * as changedModule from "${specifier}";

// The review target is loaded as a module so repository exploration can follow
// its exported surface from a real caller rather than an isolated text snippet.
export const changedExports = Object.keys(changedModule);
export const callerDepth = ${depth};
`,
	};
}

function projectFor(spec) {
	if (spec.file === "Cargo.toml" || spec.file.endsWith(".rs"))
		return { ...RUST_PROJECT };
	if (spec.file === "package.json") {
		return {
			...TYPESCRIPT_PROJECT,
			"pnpm-lock.yaml": `lockfileVersion: '9.0'\nimporters:\n  .: {}\n`,
			"app.js": `export function start() { return "ready"; }\n`,
		};
	}
	return { ...TYPESCRIPT_PROJECT, ...callerFor(spec.file) };
}

function baseContentFor(spec, files) {
	if (spec.file === "Cargo.toml") return RUST_PROJECT["Cargo.toml"];
	if (spec.file === "package.json") return TYPESCRIPT_PROJECT["package.json"];
	return files[spec.file];
}

export function defineFixtures(specs) {
	return specs.map((spec) => {
		if (!spec.id || !spec.file || typeof spec.code !== "string")
			throw new Error("fixture requires id, file, and code");
		const context = {
			...projectFor(spec),
			...(spec.contextFiles ?? {}),
		};
		const base = { ...context };
		const prior =
			spec.baseCode === undefined
				? baseContentFor(spec, context)
				: spec.baseCode;
		if (prior === undefined) delete base[spec.file];
		else base[spec.file] = prior;
		const head = { ...context, [spec.file]: spec.code };
		return {
			id: spec.id,
			...(spec.source ? { source: spec.source } : {}),
			violations: spec.violations ?? [],
			repository: { base, head, changed: [spec.file] },
		};
	});
}

function lines(text) {
	return String(text).replace(/\n$/, "").split("\n");
}

function page(text, args = {}, { numbered = false } = {}) {
	const all = text === "" ? [] : lines(text);
	const total = all.length;
	const requestedStart =
		Number.isInteger(args.start_line) && args.start_line > 0
			? args.start_line
			: 1;
	const start = Math.min(requestedStart, Math.max(total, 1));
	const requestedEnd =
		Number.isInteger(args.end_line) && args.end_line > 0
			? args.end_line
			: start + MAX_PAGE_LINES - 1;
	const end = Math.min(total, requestedEnd, start + MAX_PAGE_LINES - 1);
	return {
		content:
			total === 0
				? ""
				: all
						.slice(start - 1, end)
						.map((line, index) =>
							numbered ? `${start + index}: ${line}` : line,
						)
						.join("\n"),
		start_line: total === 0 ? 0 : start,
		end_line: total === 0 ? 0 : end,
		total_lines: total,
		truncated: end < total,
	};
}

function changeWindow(oldLines, newLines) {
	let prefix = 0;
	while (
		prefix < oldLines.length &&
		prefix < newLines.length &&
		oldLines[prefix] === newLines[prefix]
	)
		prefix++;
	let suffix = 0;
	while (
		suffix < oldLines.length - prefix &&
		suffix < newLines.length - prefix &&
		oldLines[oldLines.length - suffix - 1] ===
			newLines[newLines.length - suffix - 1]
	)
		suffix++;
	return { prefix, suffix };
}

function unifiedDiff(path, base, head) {
	const before = base[path];
	const after = head[path];
	const oldLines = before === undefined ? [] : lines(before);
	const newLines = after === undefined ? [] : lines(after);
	const { prefix, suffix } = changeWindow(oldLines, newLines);
	const contextStart = Math.max(0, prefix - 3);
	const oldChangeEnd = oldLines.length - suffix;
	const newChangeEnd = newLines.length - suffix;
	const contextEnd = Math.min(oldLines.length, oldChangeEnd + 3);
	const beforeContext = oldLines.slice(contextStart, prefix);
	const removed = oldLines.slice(prefix, oldChangeEnd);
	const added = newLines.slice(prefix, newChangeEnd);
	const afterContext = oldLines.slice(oldChangeEnd, contextEnd);
	const oldStart = oldLines.length === 0 ? 0 : contextStart + 1;
	const newStart = newLines.length === 0 ? 0 : contextStart + 1;
	const oldCount = beforeContext.length + removed.length + afterContext.length;
	const newCount = beforeContext.length + added.length + afterContext.length;
	const status =
		before === undefined
			? "new file mode 100644\n"
			: after === undefined
				? "deleted file mode 100644\n"
				: "";
	const oldPath = before === undefined ? "/dev/null" : `a/${path}`;
	const newPath = after === undefined ? "/dev/null" : `b/${path}`;
	return [
		`diff --git a/${path} b/${path}`,
		status.trimEnd(),
		`--- ${oldPath}`,
		`+++ ${newPath}`,
		`@@ -${oldStart},${oldCount} +${newStart},${newCount} @@`,
		...beforeContext.map((line) => ` ${line}`),
		...removed.map((line) => `-${line}`),
		...added.map((line) => `+${line}`),
		...afterContext.map((line) => ` ${line}`),
	]
		.filter(Boolean)
		.join("\n");
}

function changedFiles(repository) {
	return repository.changed.map((path) => {
		const before = repository.base[path];
		const after = repository.head[path];
		const oldLines = before === undefined ? [] : lines(before);
		const newLines = after === undefined ? [] : lines(after);
		const { prefix, suffix } = changeWindow(oldLines, newLines);
		return {
			status: before === undefined ? "A" : after === undefined ? "D" : "M",
			path,
			additions: newLines.length - prefix - suffix,
			deletions: oldLines.length - prefix - suffix,
		};
	});
}

function snapshot(repository, revision) {
	return revision === "base" ? repository.base : repository.head;
}

function validFixturePath(path) {
	return (
		typeof path === "string" &&
		path.length > 0 &&
		!path.startsWith("/") &&
		!path.includes("..") &&
		!path.includes("\\")
	);
}

export function createFixtureRepository(testCase) {
	const fixture = testCase.repository;
	if (!fixture?.base || !fixture?.head || !Array.isArray(fixture.changed))
		throw new Error(`${testCase.id} has no repository snapshot`);
	const changed = new Set(fixture.changed);
	const changes = changedFiles(fixture);

	async function executeTool(name, args = {}) {
		try {
			if (name === "get_changed_file_diff") {
				if (!validFixturePath(args.path) || !changed.has(args.path))
					throw new Error("path is not changed in this pull request");
				return {
					ok: true,
					path: args.path,
					...page(unifiedDiff(args.path, fixture.base, fixture.head), args),
				};
			}
			if (name === "read_file") {
				if (!validFixturePath(args.path))
					throw new Error("path must be repository-relative");
				const files = snapshot(fixture, args.revision);
				if (!(args.path in files)) throw new Error("fixture path not found");
				return {
					ok: true,
					path: args.path,
					revision: args.revision === "base" ? "base" : "head",
					...page(files[args.path], args, { numbered: true }),
				};
			}
			if (name === "search_repository") {
				if (typeof args.query !== "string" || !args.query)
					throw new Error("query must be a non-empty string");
				const files = snapshot(fixture, args.revision);
				const prefix = args.path ?? "";
				const limit = Math.min(
					Number.isInteger(args.max_results) && args.max_results > 0
						? args.max_results
						: MAX_SEARCH_RESULTS,
					MAX_SEARCH_RESULTS,
				);
				const all = Object.entries(files)
					.sort(([left], [right]) => left.localeCompare(right))
					.flatMap(([path, content]) => {
						if (prefix && path !== prefix && !path.startsWith(`${prefix}/`))
							return [];
						return lines(content).flatMap((line, index) =>
							line.includes(args.query)
								? [{ path, line: index + 1, text: line }]
								: [],
						);
					});
				return {
					ok: true,
					matches: all.slice(0, limit),
					truncated: all.length > limit,
				};
			}
			if (name === "list_repository") {
				const files = snapshot(fixture, args.revision);
				const prefix = args.path ?? "";
				const limit = Math.min(
					Number.isInteger(args.max_results) && args.max_results > 0
						? args.max_results
						: MAX_LIST_RESULTS,
					MAX_LIST_RESULTS,
				);
				const paths = Object.keys(files)
					.sort()
					.filter(
						(path) =>
							!prefix || path === prefix || path.startsWith(`${prefix}/`),
					);
				return {
					ok: true,
					paths: paths.slice(0, limit),
					truncated: paths.length > limit,
				};
			}
			throw new Error(`unknown repository tool: ${name}`);
		} catch (error) {
			return { ok: false, error: String(error?.message ?? error) };
		}
	}

	return {
		baseSha: `fixture-${testCase.id}-base`,
		headSha: `fixture-${testCase.id}-head`,
		changes,
		executeTool,
		getRawDiff(path) {
			if (!changed.has(path))
				throw new Error("path is not changed in this pull request");
			return unifiedDiff(path, fixture.base, fixture.head);
		},
		validateFinding({ file, line, quote }) {
			if (!changed.has(file)) return false;
			const { newLines } = parseDiff(
				unifiedDiff(file, fixture.base, fixture.head),
			);
			const claimed = newLines.find(
				(candidate) => candidate.added && candidate.line === line,
			);
			return Boolean(claimed && claimed.text.includes(String(quote).trim()));
		},
	};
}
